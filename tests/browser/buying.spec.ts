test("Vultr microphone briefing, live extraction and spoken decision work through registered actions", async ({ page }, info) => {
  // guard:allow-env-credential — Explicit non-secret opt-in to actual provider requests during a browser check.
  test.skip(process.env.SHORTLIST_LIVE_AI !== "true", "Live Vultr requests require an explicit test opt-in.");
  test.setTimeout(240_000);
  await openExample(page, new URL(info.project.use.baseURL!).origin);
  const initialSession = await (await page.request.get("/_agent-native/auth/session")).json();
  expect(typeof initialSession.orgId).toBe("string");
  await page.getByRole("button", { name: "Speak or type a brief" }).click();
  await page.getByRole("button", { name: "Record", exact: false }).click();
  await expect(page.getByRole("button", { name: "Stop recording" })).toBeVisible();
  await page.waitForTimeout(14_000);
  await page.getByRole("button", { name: "Stop recording" }).click();
  await expect(page.getByRole("heading", { name: "Review before saving" })).toBeVisible({ timeout: 120_000 });
  await expect(page.getByLabel("Brief quantity", { exact: true })).toHaveValue("100");
  await expect(page.getByLabel("Brief complete budget", { exact: true })).toHaveValue("590.00");
  await page.getByRole("button", { name: "Save reviewed requirements" }).click();
  await expect(page.getByRole("dialog")).not.toBeVisible();
  await expect(page.getByRole("textbox", { name: "Total budget", exact: true })).toHaveValue("590.00");
  const id = new URL(page.url()).searchParams.get("decision")!;
  await page.getByRole("button", { name: "Edit Cedar Print Delivery date" }).click();
  await page.getByRole("dialog").locator('input[name="value"]').fill("2026-11-18");
  await page.getByRole("dialog").locator('input[name="note"]').fill("Supplier confirmed delivery is delayed");
  await page.getByRole("button", { name: "Save correction" }).click();
  await expect(page.getByTestId("recommendation")).toHaveText("No suitable offer");
  await page.getByRole("button", { name: "Replace source", exact: true }).click();
  const source = page.getByRole("dialog").locator("textarea");
  await source.fill((await source.inputValue()).replace("$5.40 USD", "$5.10 USD"));
  await page.getByRole("dialog").getByRole("button", { name: "Replace source", exact: true }).click();
  // Cover the first-session scope refresh that used to cancel a delayed chat
  // submission before it reached the model, despite shorter flows passing.
  await page.waitForTimeout(35_000);
  await page.getByRole("button", { name: "Review with agent", exact: false }).click();
  await page.getByRole("button", { name: "Continue with the agent", exact: false }).click();
  await expect.poll(async () => {
    const response = await page.request.get("/_agent-native/actions/get-decision", { params: { id } });
    const view = await response.json();
    const cedar = view.state.quotes.find((q: { supplier: string }) => q.supplier === "Cedar Print");
    expect(cedar.fields.deliveryDate.value).toBe("2026-11-18"); expect(cedar.fields.deliveryDate.locked).toBe(true);
    return view.events.some((event: { actor: string; kind: string }) => event.actor === "agent" && event.kind === "extraction") && cedar.fields.unitMinor.value === 510;
  }, { timeout: 120_000, intervals: [1000, 2500] }).toBe(true);
  const chatSession = await (await page.request.get("/_agent-native/auth/session")).json();
  expect(chatSession.orgId).toBe(initialSession.orgId);
  await page.getByRole("button", { name: "Hear the decision" }).click();
  const audio = page.getByLabel("Spoken decision explanation");
  await expect(audio).toBeVisible({ timeout: 90_000 });
  await expect.poll(() => audio.evaluate((element: HTMLAudioElement) => element.readyState >= 2 && element.duration > 1)).toBe(true);
  await audio.evaluate((element: HTMLAudioElement) => element.play());
  await expect.poll(() => audio.evaluate((element: HTMLAudioElement) => element.currentTime > .2)).toBe(true);
});
