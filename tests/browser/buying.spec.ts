import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";
import { randomUUID } from "node:crypto";

async function openExample(page: import("@playwright/test").Page, origin: string) {
  const signUp = await page.request.post("/_agent-native/auth/ba/sign-up/email", { headers: { Origin: origin }, data: { email: "buying-" + randomUUID() + "@example.invalid", name: "Buying verification", password: "Check-" + randomUUID() + "-aA1" } });
  expect(signUp.ok()).toBeTruthy();
  await page.goto("/home"); await page.getByRole("button", { name: "Try the example" }).click();
  await expect(page.getByTestId("recommendation")).toHaveText("Cedar Print");
  await expect(page.getByText("Configuration error", { exact: false })).toHaveCount(0);
}

